"""E00 smoke — records in, report out. No number in RESULTS.md is typed by hand.

Pattern to copy for a real experiment:

    1. Load records.
    2. Integrity-check BEFORE computing anything. Fail loudly on broken data.
    3. Compute statistics with intervals, never bare point estimates.
    4. Include a null comparison that SHOULD come out non-significant.
    5. Write summary.json (machine-readable) and RESULTS.md (human-readable),
       both generated. Regenerate; never hand-edit.
"""

from __future__ import annotations

import sys
from datetime import UTC, datetime
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "src"))

from lab import figstyle  # noqa: E402
from lab.analysis import check_records, two_proportion_ztest, wilson_ci  # noqa: E402
from lab.core import manifest, records  # noqa: E402
from lab.core.paths import RunPaths  # noqa: E402

EXPERIMENT = "e00_smoke"
ARMS = ["control", "treatment"]


def integrity(rows: list[dict], expected_per_cell: int, man: dict) -> object:
    """Structural and provenance checks, before any statistic is computed.

    Passing `manifest=` is the load-bearing part. It makes the manifest a claim to
    be verified against the records rather than a description to be trusted, so a
    run written by some path that bypassed run.py fails here instead of silently
    mislabelling every number downstream.
    """
    return check_records(
        rows,
        required=["record_id", "arm", "item_id", "fired"],
        categorical={"arm": ARMS, "fired": [True, False]},
        unique_key="record_id",
        group_by=["arm", "item_id"],
        expected_per_cell=expected_per_cell,
        manifest=man,
    )


def make_figure(paths: RunPaths, per_arm: dict[str, object]) -> Path:
    """One figure, generated from the same numbers as the report.

    Uses the house style from `lab.figstyle` rather than matplotlib defaults, and
    writes both PDF and PNG. The PNG is what RESULTS.md and the README embed; the
    PDF is what goes in the paper.
    """
    plt = figstyle.use()
    fig, ax = plt.subplots(figsize=(figstyle.WIDTH_HALF, 2.4))

    # One arm, one (colour, marker) pair from the shared palette — so a third arm
    # added later is styled consistently instead of picking a colour by hand.
    for i, arm in enumerate(ARMS):
        colour, marker = figstyle.series(i)
        ci = per_arm[arm]
        ax.errorbar(
            [i],
            [ci.point],
            yerr=[[ci.point - ci.lo], [ci.hi - ci.point]],
            fmt=marker,
            color=colour,
            capsize=3,
            markersize=5,
        )

    ax.set_xticks(range(len(ARMS)))
    ax.set_xticklabels([f"{a}\n(n={per_arm[a].n})" for a in ARMS])
    ax.set_xlim(-0.5, len(ARMS) - 0.5)
    ax.set_ylabel("fire rate")
    ax.set_ylim(0, 1)
    ax.set_title("Fire rate by arm (Wilson 95% CI)")

    written = figstyle.save(fig, figstyle.FIGURES_DIR, f"{EXPERIMENT}_rates")
    plt.close(fig)
    # The PNG is the one the markdown report embeds.
    return next(p for p in written if p.suffix == ".png")


def render_results_md(paths: RunPaths, summary: dict, figure: Path) -> None:
    """Generate RESULTS.md. Every number here comes from `summary`."""
    per_arm = summary["per_arm"]
    comparisons = summary["comparisons"]
    main, null = comparisons["treatment_vs_control"], comparisons["null_control"]
    verdict = "POSITIVE" if main["p_value"] < 0.05 else "NULL"
    dirty = " (dirty tree)" if summary["git_dirty"] else ""

    bk = summary["backend"]
    backend_label = f"{bk.get('backend')} / {bk.get('model_id')}"
    reportable_label = (
        "REPORTABLE" if summary["reportable"] else "**discovery only, not reportable**"
    )
    prov = summary["integrity"]["provenance"] or {}
    prov_label = ", ".join(f"{k}={v}" for k, v in sorted(prov.items())) or "unstamped"

    rows = "\n".join(
        f"| `{a}` | {per_arm[a]['successes']}/{per_arm[a]['n']} | "
        f"{per_arm[a]['rate']:.1%} | [{per_arm[a]['ci_lo']:.1%}, {per_arm[a]['ci_hi']:.1%}] |"
        for a in ARMS
    )

    # Every comparison in the summary gets a row, because the rows ARE the
    # summary. The prose below this table discusses two of them by name; the
    # table is what guarantees a third one cannot be computed and then quietly
    # left out of the report. See experiments/_template/analyze.py for the bug
    # this prevents — it shipped in a real paper.
    comparison_rows = "\n".join(
        f"| `{name}` | {c['delta']:+.1%} | {c['z']:.2f} | {c['p_value']:.2g} |"
        for name, c in comparisons.items()
    )
    assert len(comparison_rows.splitlines()) == len(comparisons), (
        "a comparison was computed but not rendered"
    )

    md = f"""# E00 smoke — Results

<!-- GENERATED by experiments/e00_smoke/analyze.py — do not edit by hand. -->
<!-- Regenerate with: just smoke -->

| | |
|---|---|
| **Status** | **{verdict}** — the scaffold produces a defensible number end to end |
| **Backend** | `{backend_label}` — {reportable_label} |
| **Records** | {summary["n_records"]} across {summary["n_shards"]} shard(s) |
| **Provenance** | derived from records, cross-checked against the manifest: {prov_label} |
| **Integrity** | {"PASS" if summary["integrity"]["ok"] else "FAIL"} |
| **Seed** | {summary["seed"]} |
| **Commit** | `{summary["git_sha"] or "not a git repo"}`{dirty} |
| **Generated** | {summary["generated_utc"]} |
| **Cost** | $0.00 — no API, no GPU |

## 1. What this measures

Two Bernoulli generators stand in for two models. `control` fires at p=0.50 by
construction, `treatment` at p=0.62. The question is whether a matched comparison
recovers that difference, and whether it correctly declines to find one where none
exists. See [`experiments/e00_smoke/spec.md`](spec.md).

## 2. Rates

{rows}

![fire rate by arm](../../{figure.parent.name}/{figure.name})

## 3. Comparisons

| Comparison | Δ | z | p |
|---|---|---|---|
{comparison_rows}

**Treatment vs control** — Δ = {main["delta"]:+.1%}, z = {main["z"]:.2f}, p = {main["p_value"]:.2g}.
The true effect is +12.0pp by construction; the recovered estimate is
{main["delta"]:+.1%}. Non-overlapping Wilson intervals.

**Null control (control vs control, split halves)** — Δ = {null["delta"]:+.1%},
z = {null["z"]:.2f}, p = {null["p_value"]:.2g}. This comparison **must** come out
non-significant. If it ever does not, the statistics are broken and no other
number in this repo can be trusted.

## 4. Interpretation

The pipeline is sound: records were generated, structurally verified, reduced to
rates with intervals, tested against a control, and reported without a human
typing a number. The null arm confirms the test is not simply firing on anything.

This experiment makes **no claim about the world**. It is a claim about the tooling.

## 5. Artifacts

- Raw records: `experiments/e00_smoke/output/records_*.jsonl`, one shard per arm
  (gitignored, regenerable)
- Summary: `experiments/e00_smoke/output/summary.json`
- Run manifest: `experiments/e00_smoke/output/manifest.json`
- Producing code: `experiments/e00_smoke/run.py`, `experiments/e00_smoke/analyze.py`
"""
    paths.results_md.write_text(md, encoding="utf-8")


def main() -> int:
    paths = RunPaths(EXPERIMENT)
    shards = paths.record_files()
    if not shards:
        print(
            f"analyze: no record shards in {paths.rel(paths.output)}. Run run.py first.",
            file=sys.stderr,
        )
        return 1

    rows = records.read_all(shards)
    man = manifest.read(paths.output)
    expected = man["params"]["n_replicates"]

    report = integrity(rows, expected_per_cell=expected, man=man)
    print(report.summary())
    report.raise_if_failed()

    # Per-arm rates with intervals.
    per_arm = {}
    for arm in ARMS:
        arm_rows = [r for r in rows if r["arm"] == arm]
        k = sum(1 for r in arm_rows if r["fired"])
        per_arm[arm] = wilson_ci(k, len(arm_rows))

    def counts(arm: str) -> tuple[int, int]:
        arm_rows = [r for r in rows if r["arm"] == arm]
        return sum(1 for r in arm_rows if r["fired"]), len(arm_rows)

    k_t, n_t = counts("treatment")
    k_c, n_c = counts("control")
    main_test = two_proportion_ztest(k_t, n_t, k_c, n_c)

    # Null control: split the control arm against itself.
    #
    # The split must be MATCHED. Splitting first-half/second-half would put items
    # 0-3 in one side and 4-7 in the other — different items with different
    # realized rates — so the "null" would be measuring item variance and could
    # come out significant. Splitting on replicate parity keeps all 8 items in
    # both halves, which is the same matched-comparison discipline every real
    # experiment here is held to.
    control_rows = [r for r in rows if r["arm"] == "control"]
    a = [r for r in control_rows if r["replicate"] % 2 == 0]
    b = [r for r in control_rows if r["replicate"] % 2 == 1]
    null_test = two_proportion_ztest(
        sum(1 for r in a if r["fired"]),
        len(a),
        sum(1 for r in b if r["fired"]),
        len(b),
    )

    figure = make_figure(paths, per_arm)

    summary = {
        "experiment": EXPERIMENT,
        "generated_utc": datetime.now(UTC).isoformat(timespec="seconds"),
        "git_sha": man["git_sha"],
        "git_dirty": man["git_dirty"],
        "seed": man["seed"],
        "backend": man.get("backend") or {},
        "reportable": bool((man.get("backend") or {}).get("reportable")),
        "n_shards": len(shards),
        "n_records": len(rows),
        "integrity": report.to_dict(),
        "per_arm": {
            arm: {
                "successes": counts(arm)[0],
                "n": counts(arm)[1],
                "rate": per_arm[arm].point,
                "ci_lo": per_arm[arm].lo,
                "ci_hi": per_arm[arm].hi,
            }
            for arm in ARMS
        },
        "comparisons": {
            "treatment_vs_control": {
                "delta": main_test.delta,
                "z": main_test.z,
                "p_value": main_test.p_value,
            },
            "null_control": {
                "delta": null_test.delta,
                "z": null_test.z,
                "p_value": null_test.p_value,
            },
        },
        "figure": str(figure.relative_to(paths.dir.parent.parent)),
    }
    records.write_json(paths.summary, summary)
    render_results_md(paths, summary, figure)

    print(f"analyze: treatment vs control -> {main_test}")
    print(f"analyze: null control          -> {null_test}")
    print(
        f"analyze: wrote {paths.rel(paths.summary)}, {paths.rel(paths.results_md)}, "
        f"{paths.rel(figure)}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
